/** Drapeau emoji d'un pays (🏳️ si aucun drapeau officiel). */
export function flagOf(atlas: string): string {
  const iso = ISO2[atlas];
  if (!iso) return '🏳️';
  return String.fromCodePoint(...[...iso.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}
